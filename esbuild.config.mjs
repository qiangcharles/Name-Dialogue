import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

const stylesContext = await esbuild.context({
	entryPoints: ['src/css/index.css'],
	bundle: true,
	logLevel: 'info',
	outfile: 'styles.css',
	minify: prod,
	banner: {
		css: '/* styles.css is generated from the .css files in /src/css/. */',
	},
});

if (prod) {
	await Promise.all([context.rebuild(), stylesContext.rebuild()]);
	process.exit(0);
} else {
	await Promise.all([context.watch(), stylesContext.watch()]);
}
